    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    room_id BIGINT NOT NULL,
    sprint_no INTEGER NOT NULL,
    name VARCHAR(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    started_by_account_id BIGINT NOT NULL,
    closed_by_account_id BIGINT,
    closed_at TIMESTAMP(6),
    total_task_count INTEGER,
    done_task_count INTEGER,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_sprint PRIMARY KEY (id),
