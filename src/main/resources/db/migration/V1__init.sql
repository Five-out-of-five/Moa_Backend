-- 회원 계정 (소셜 로그인 전용, 소셜 연결·약관 동의 포함)
CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider VARCHAR(20) NOT NULL,
    provider_uid VARCHAR(255),
    email VARCHAR(255),
    name VARCHAR(50),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    suspended_until TIMESTAMP(6),
    tone_mode VARCHAR(20) NOT NULL DEFAULT 'POLISH',
    last_room_id BIGINT,
    report_blocked_until TIMESTAMP(6),
    last_login_at TIMESTAMP(6),
    terms_agreed_at TIMESTAMP(6) NOT NULL,
    privacy_agreed_at TIMESTAMP(6) NOT NULL,
    purge_at TIMESTAMP(6),
    deleted_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_account PRIMARY KEY (id),
    CONSTRAINT ck_account_provider CHECK (provider IN ('GOOGLE', 'KAKAO', 'NAVER')),
    CONSTRAINT ck_account_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    CONSTRAINT ck_account_tone_mode CHECK (tone_mode IN ('OFF', 'POLISH', 'POLITE'))
);

