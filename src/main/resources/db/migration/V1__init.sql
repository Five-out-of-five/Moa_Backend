    CONSTRAINT ck_room_widget_bound CHECK (pos_x + width <= 12),
    CONSTRAINT ck_room_widget_min_size CHECK (CASE widget_type WHEN 'IDEA_BOARD' THEN width >= 6 AND height >= 5 WHEN 'TASK_BOARD' THEN width >= 4 AND height >= 4 WHEN 'PROGRESS' THEN width >= 2 AND height >= 2 ELSE width >= 3 AND height >= 3 END)
